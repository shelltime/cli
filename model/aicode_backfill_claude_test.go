// writeJSONL writes one line per value: strings are written as is (to
// simulate corrupt lines), anything else is JSON encoded.
func writeJSONL(t *testing.T, path string, lines ...any) {
	t.Helper()
	require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o755))
	var b strings.Builder
	for _, l := range lines {
		if s, ok := l.(string); ok {
			b.WriteString(s)
		} else {
			buf, err := json.Marshal(l)
			require.NoError(t, err)
			b.Write(buf)
		}
		b.WriteString("\n")
	}
	require.NoError(t, os.WriteFile(path, []byte(b.String()), 0o644))
}

type obj = map[string]any

func claudeTS(min, sec int) string {
	return time.Date(2026, 9, 10, 10, min, sec, 0, time.UTC).Format("2006-01-02T15:04:05.000Z")
}

func claudeUser(session, uuid, ts string, content any, extra obj) obj {
	l := obj{
		"type": "user", "uuid": uuid, "sessionId": session, "timestamp": ts,
		"cwd": "/tmp/proj", "version": "2.1.0",
		"message": obj{"role": "user", "content": content},
	}
	for k, v := range extra {
		l[k] = v
	}
	return l
}

func claudeAssistant(session, uuid, ts, msgID, reqID string, blocks []any, usage obj, extra obj) obj {
	l := obj{
		"type": "assistant", "uuid": uuid, "sessionId": session, "timestamp": ts,
		"cwd": "/tmp/proj", "version": "2.1.0", "requestId": reqID,
		"message": obj{"id": msgID, "model": "claude-sonnet-4-5", "role": "assistant", "content": blocks, "usage": usage},
	}
	for k, v := range extra {
		l[k] = v
	}
	return l
}

func usage(in, out, cacheCreate, cacheRead int) obj {
	return obj{"input_tokens": in, "output_tokens": out, "cache_creation_input_tokens": cacheCreate, "cache_read_input_tokens": cacheRead}
}

func sessionByID(t *testing.T, res *BackfillParseResult, id string) *BackfillSession {
	t.Helper()
	for _, s := range res.Sessions {
		if s.ID == id {
			return s
		}
	}
	t.Fatalf("session %s not found", id)
	return nil
}

func eventsOfType(s *BackfillSession, eventType string) []AICodeBackfillEvent {
	var out []AICodeBackfillEvent
	for _, e := range s.Events {
		if e.EventType == eventType {
			out = append(out, e)
		}
	}
	return out
}

