func TestParseClaudeTranscripts(t *testing.T) {
	root, root2 := writeClaudeFixtures(t)
	t.Setenv("CLAUDE_CONFIG_DIR", root+", "+root2)

	res, err := ParseClaudeTranscripts(ClaudeProjectRoots(), BackfillOptions{})
	require.NoError(t, err)

	assert.Equal(t, 4, res.Files)
	assert.Equal(t, 1, res.BadLines)
	require.Len(t, res.Sessions, 3)

	a := sessionByID(t, res, "sess-a")
	prompts := eventsOfType(a, AICodeEventUserPrompt)
	require.Len(t, prompts, 2)
	assert.Equal(t, "Fix the bug", prompts[0].Prompt)
	assert.Equal(t, 11, *prompts[0].PromptLength)
	assert.Equal(t, "/review PR 12", prompts[1].Prompt)

	requests := eventsOfType(a, AICodeEventApiRequest)
	require.Len(t, requests, 4, "msg_1 once, msg_2 credited to the original session, msg_3, subagent msg_5")
	assert.Equal(t, 50, *requests[0].OutputTokens, "the most complete usage line wins")
	assert.Equal(t, 1000, *requests[0].CacheReadTokens)
	assert.Equal(t, 100, *requests[0].CacheCreationTokens)
	assert.Nil(t, requests[0].CostUSD)
	assert.InDelta(t, 0.01, *requests[1].CostUSD, 1e-9)
	assert.Equal(t, 20, *requests[3].InputTokens, "subagent usage belongs to the parent session")

	apiErrors := eventsOfType(a, AICodeEventApiError)
	require.Len(t, apiErrors, 1)
	assert.Equal(t, "API Error: 529 overloaded", apiErrors[0].Error)
	assert.Empty(t, apiErrors[0].Model)
	assert.Nil(t, apiErrors[0].InputTokens)

	tools := eventsOfType(a, AICodeEventToolResult)
	require.Len(t, tools, 2)
	assert.Equal(t, "Edit", tools[0].ToolName)
	assert.Equal(t, false, *tools[0].Success)
	assert.Nil(t, tools[0].DurationMs)
	assert.Equal(t, map[string]any{"file_path": "/tmp/proj/a.go"}, tools[0].ToolParameters)
	assert.Equal(t, "Bash", tools[1].ToolName)
	assert.Equal(t, true, *tools[1].Success)
	assert.Equal(t, 1234, *tools[1].DurationMs)
	assert.Nil(t, tools[1].ToolParameters, "commands are never uploaded")

	for _, e := range a.Events {
		assert.Equal(t, AICodeClientClaudeCode, e.ClientType)
		assert.Equal(t, "sess-a", e.SessionID)
		assert.Equal(t, "/tmp/proj", e.Pwd)
		assert.Equal(t, "2.1.0", e.AppVersion)
		assert.Equal(t, "shelltime", e.TeamID)
		assert.Regexp(t, `^bf1:[0-9a-f]{40}$`, e.EventID)
	}
	assert.Equal(t, time.Date(2026, 9, 10, 10, 0, 0, 0, time.UTC), a.Start.UTC())

	b := sessionByID(t, res, "sess-b")
	assert.Len(t, eventsOfType(b, AICodeEventApiRequest), 1, "copied history is not counted twice")
	assert.Len(t, eventsOfType(b, AICodeEventUserPrompt), 1)

	c := sessionByID(t, res, "sess-c")
	require.Len(t, c.Events, 2)
	assert.Equal(t, "Old style prompt", eventsOfType(c, AICodeEventUserPrompt)[0].Prompt)
	cReq := eventsOfType(c, AICodeEventApiRequest)[0]
	assert.InDelta(t, 0.5, *cReq.CostUSD, 1e-9)
	assert.Equal(t, 0, *cReq.CacheReadTokens)
	assert.Equal(t, "/tmp/other", cReq.Pwd)
	assert.Equal(t, "1.0.0", cReq.AppVersion)
}

func TestParseClaudeTranscriptsIDsDoNotDependOnSession(t *testing.T) {
	root, root2 := writeClaudeFixtures(t)
	res, err := ParseClaudeTranscripts([]string{filepath.Join(root, "projects"), filepath.Join(root2, "projects")}, BackfillOptions{})
	require.NoError(t, err)

	ids := map[string]bool{}
	for _, s := range res.Sessions {
		for _, e := range s.Events {
			assert.False(t, ids[e.EventID], "duplicate event id %s", e.EventID)
			ids[e.EventID] = true
		}
	}
	assert.True(t, ids[backfillEventID(AICodeClientClaudeCode, "api:msg_2:req_2")])
	assert.True(t, ids[backfillEventID(AICodeClientClaudeCode, "prompt:u1")])
	assert.True(t, ids[backfillEventID(AICodeClientClaudeCode, "tool:toolu_1")])
}

func TestParseClaudeTranscriptsNoPrompts(t *testing.T) {
	root, _ := writeClaudeFixtures(t)
	res, err := ParseClaudeTranscripts([]string{filepath.Join(root, "projects")}, BackfillOptions{NoPrompts: true})
	require.NoError(t, err)

	prompts := eventsOfType(sessionByID(t, res, "sess-a"), AICodeEventUserPrompt)
	require.Len(t, prompts, 2)
	assert.Empty(t, prompts[0].Prompt)
	assert.Equal(t, 11, *prompts[0].PromptLength)
}

func TestParseClaudeTranscriptsCapsLongPrompts(t *testing.T) {
	root := t.TempDir()
	long := strings.Repeat("é", backfillMaxPromptBytes)
	writeJSONL(t, filepath.Join(root, "p", "s.jsonl"),
		claudeUser("s", "u1", claudeTS(0, 0), long, obj{"origin": obj{"kind": "human"}}))

	res, err := ParseClaudeTranscripts([]string{root}, BackfillOptions{})
	require.NoError(t, err)

	e := res.Sessions[0].Events[0]
	assert.LessOrEqual(t, len(e.Prompt), backfillMaxPromptBytes)
	assert.True(t, strings.HasPrefix(long, e.Prompt))
	assert.Equal(t, backfillMaxPromptBytes, *e.PromptLength, "the length reports the full prompt")
}

